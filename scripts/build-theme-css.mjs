import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const compactPages = ["index.html", path.join("professional", "index.html")];

// Keep the full desktop stylesheet as the source of truth. Compact pages get
// the same cascade, without selectors for desktop windows and other unused UI.
export async function buildThemeCss() {
  const source = await readFile(path.join(root, "styles.css"), "utf8");
  const markup = (await Promise.all(compactPages.map((file) => (
    readFile(path.join(root, file), "utf8")
  )))).join("\n");
  const classes = new Set(["is-rgb-mode", "is-performance-lite", "is-page-hidden"]);
  const ids = new Set();
  for (const [, value] of markup.matchAll(/\bclass="([^"]*)"/g)) {
    value.split(/\s+/).forEach((name) => classes.add(name));
  }
  for (const [, value] of markup.matchAll(/\bid="([^"]*)"/g)) {
    ids.add(value);
  }
  const keyframes = [];

  function splitSelectors(value) {
    const selectors = [];
    let depth = 0;
    let start = 0;
    let quote = "";
    for (let index = 0; index < value.length; index += 1) {
      const char = value[index];
      if (quote) {
        if (char === "\\") {
          index += 1;
        } else if (char === quote) {
          quote = "";
        }
      } else if (char === '"' || char === "'") {
        quote = char;
      } else if (char === "(" || char === "[") {
        depth += 1;
      } else if (char === ")" || char === "]") {
        depth -= 1;
      } else if (char === "," && depth === 0) {
        selectors.push(value.slice(start, index));
        start = index + 1;
      }
    }
    selectors.push(value.slice(start));
    return selectors;
  }

  function isShared(selector) {
    const withoutAttributes = selector.replace(/\[[^\]]*\]/g, "");
    const tokens = [...withoutAttributes.matchAll(/([.#])([\w-]+)/g)];
    const known = ([, prefix, name]) => (prefix === "." ? classes : ids).has(name);
    // A grouped :is() rule can share one declaration between desktop and
    // compact controls. Keep the whole group when any compact control uses it.
    return tokens.every(known) || (selector.includes(":is(") && tokens.some(known));
  }

  function filterRules(css) {
    let start = 0;
    let depth = 0;
    let quote = "";
    let comment = false;
    let opening = 0;
    let result = "";
    for (let index = 0; index < css.length; index += 1) {
      const char = css[index];
      if (comment) {
        if (char === "*" && css[index + 1] === "/") {
          comment = false;
          index += 1;
        }
        continue;
      }
      if (quote) {
        if (char === "\\") {
          index += 1;
        } else if (char === quote) {
          quote = "";
        }
        continue;
      }
      if (char === "/" && css[index + 1] === "*") {
        comment = true;
        index += 1;
        continue;
      }
      if (char === '"' || char === "'") {
        quote = char;
        continue;
      }
      if (char === "{") {
        if (depth === 0) {
          opening = index;
        }
        depth += 1;
      } else if (char === "}") {
        depth -= 1;
        if (depth !== 0) {
          continue;
        }
        const header = css.slice(start, opening).replace(/\/\*[\s\S]*?\*\//g, "").trim();
        const body = css.slice(opening + 1, index);
        start = index + 1;
        if (/^@(?:-\w+-)?keyframes\b/.test(header)) {
          keyframes.push({ header, body });
        } else if (/^@property\b/.test(header)) {
          result += `${header} {${body}}\n\n`;
        } else if (header.startsWith("@")) {
          const children = filterRules(body);
          if (children.trim()) {
            result += `${header} {\n${children}}\n\n`;
          }
        } else {
          const selectors = splitSelectors(header).map((value) => value.trim()).filter(isShared);
          if (selectors.length) {
            result += `${selectors.join(",\n")} {${body}}\n\n`;
          }
        }
      }
    }
    if (depth !== 0 || quote || comment) {
      throw new Error("Unbalanced stylesheet while building shared theme CSS.");
    }
    return result;
  }

  let css = filterRules(source);
  for (const { header, body } of keyframes) {
    const name = header.split(/\s+/)[1];
    if (new RegExp(`\\b${name}\\b`).test(css)) {
      css += `${header} {${body}}\n\n`;
    }
  }
  return `/* Generated by node scripts\\build-theme-css.mjs; edit styles.css instead. */\n\n${css}`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = await buildThemeCss();
  await writeFile(path.join(root, "theme-base.css"), css);
  console.log(`theme-base.css: ${Buffer.byteLength(css)} bytes`);
}
